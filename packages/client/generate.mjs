#!/usr/bin/env node
// Generates the FULL contract (tools/api/openapi-full.mjs) from the kernel source, vendors it, and generates src/kernel.d.ts (openapi-typescript 7.x).
// `--check` regenerates to memory and fails if src/kernel.d.ts differs. Read-only on the kernel.
import { readFileSync, writeFileSync, existsSync, copyFileSync } from 'node:fs'; import { join, dirname } from 'node:path'; import { fileURLToPath } from 'node:url'; import { execFileSync } from 'node:child_process';
import openapiTS, { astToString } from 'openapi-typescript';
const HERE = dirname(fileURLToPath(import.meta.url));
const KERNEL = process.env.MR_KERNEL_ROOT ?? '';
const SRC = join(KERNEL, 'packages/contracts/openapi/massrelay.json');
const SNAP = join(HERE, 'openapi/massrelay-full.json'), PUBLIC = join(HERE, 'openapi/massrelay.json'), SOURCE = join(HERE, 'openapi/SOURCE.json'), OUT = join(HERE, 'src/kernel.d.ts');
const check = process.argv.includes('--check');
const read = (p) => JSON.parse(readFileSync(p, 'utf8').replace(/^﻿/, ''));
let note = '';
if (!check && existsSync(SRC)) {
  copyFileSync(SRC, PUBLIC); // the kernel's own published contract, kept for comparison
  execFileSync('node', [join(HERE, '../../tools/api/openapi-full.mjs')], { stdio: 'inherit' }); // L4: the FULL contract from the kernel source (M1 answered here)
  const sha = execFileSync('git', ['-C', KERNEL, 'rev-parse', '--short', 'HEAD'], { encoding: 'utf8' }).trim();
  const prev = existsSync(SOURCE) ? read(SOURCE) : null;
  const paths = Object.keys(read(PUBLIC).paths).length, full_paths = Object.keys(read(SNAP).paths).length;
  // keep generated_at stable when nothing changed, so a re-run leaves no diff
  const generated_at = prev && prev.kernel_sha === sha && prev.paths === paths && prev.full_paths === full_paths ? prev.generated_at : new Date().toISOString();
  writeFileSync(SOURCE, JSON.stringify({ kernel_sha: sha, paths, full_paths, generated_at }) + '\n');
} else if (!check) {
  note = `NOTE kernel not on disk — using the vendored snapshot ${read(SOURCE).kernel_sha}\n`;
}
const doc = read(SNAP);
const generated = `// GENERATED by packages/client/generate.mjs from openapi/massrelay-full.json (kernel ${read(SOURCE).kernel_sha}) — do not edit.\n` + astToString(await openapiTS(doc));
if (check) {
  if (!existsSync(OUT) || readFileSync(OUT, 'utf8') !== generated) { console.error('client:check src/kernel.d.ts is stale — run npm run client:generate'); process.exit(1); }
  console.log(`client generate --check ok: ${Object.keys(doc.paths).length} paths`);
} else {
  writeFileSync(OUT, generated);
  process.stdout.write(note);
  console.log(`client generated: ${Object.keys(doc.paths).length} paths -> src/kernel.d.ts`);
}
